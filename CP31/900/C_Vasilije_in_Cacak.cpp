        ll rem = n-k;
        ll sumOfSmall = ((rem+1) * rem)/2;
        ll largest = sum - sumOfSmall; //To extract last k numbers ,[1...k..n]
        if(x < smallest || x > largest ){
            cout<<"NO\n";return;
        }//Always createable ,assuming u used i ,then we can simply use (i+1) to get the next sum
